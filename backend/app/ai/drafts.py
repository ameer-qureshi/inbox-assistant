"""AI reply drafts and the daily summary.

Drafts are generated by the backend directly (not n8n) because the user is
waiting for them in the UI: one synchronous call is simpler and faster.
They are NEVER sent automatically: the user edits and validates them first.
"""

from __future__ import annotations

import json

from pydantic import BaseModel, Field, ValidationError

from app.ai.client import AIError, chat_json
from app.ai.masking import mask_sensitive
from app.config import get_settings
from app.models import Email

TONES = {
    "formal": "Formal and polite, full sentences, a courteous greeting and closing.",
    "neutral": "Friendly and professional, clear, 3 to 6 sentences.",
    "short": "Very short: 1 to 3 sentences, straight to the point.",
}


class DraftOutput(BaseModel):
    body: str = Field(min_length=5, max_length=5000)


class SummaryOutput(BaseModel):
    summary: str = Field(min_length=10, max_length=1200)


def _thread_context(email: Email, limit: int = 6) -> str:
    parts = []
    for m in email.thread.emails[-limit:]:
        who = "Me" if m.is_outbound else f"{m.from_name} <{m.from_address}>"
        parts.append(f"--- {who}, {m.received_at:%Y-%m-%d %H:%M}\n"
                     f"{mask_sensitive(m.body_text)[:1500]}")
    return "\n".join(parts)


def generate_draft(email: Email, tone: str) -> tuple[str, str]:
    """Returns (body, model_name). Falls back to a template in demo mode."""
    s = get_settings()
    if not s.ai_enabled:
        return _demo_draft(email, tone), "demo-template"

    messages = [
        {"role": "system", "content": (
            "You write email replies on behalf of the user. "
            f"Tone: {TONES[tone]} "
            "Reply in the same language as the last message. Never invent facts, "
            "prices, dates or commitments: use [placeholders] for anything unknown. "
            "Do not include a subject line. Values like [PHONE] or [IBAN] are masked. "
            'Return ONLY JSON: {"body": "<the reply text>"}')},
        {"role": "user", "content": (
            f"Conversation (oldest first):\n{_thread_context(email)}\n\n"
            f"Write the reply to the last message (subject: {email.subject}).")},
    ]
    for _ in range(2):  # one retry if the JSON is invalid
        raw = chat_json(s.draft_model, messages, max_tokens=1500, temperature=0.4)
        try:
            return DraftOutput.model_validate(json.loads(raw)).body.strip(), s.draft_model
        except (json.JSONDecodeError, ValidationError):
            continue
    raise AIError("AI returned an invalid draft twice")


def _demo_draft(email: Email, tone: str) -> str:
    name = email.from_name.split(" ")[0] if email.from_name else ""
    if tone == "short":
        return f"Hi {name},\n\nThanks for your message, I'll get back to you shortly.\n\nBest,"
    if tone == "formal":
        return (f"Dear {email.from_name or 'Sir or Madam'},\n\nThank you for your email "
                f"regarding \"{email.subject}\". I have taken note of your request and "
                "will reply with a detailed answer as soon as possible.\n\nKind regards,")
    return (f"Hi {name},\n\nThanks for reaching out about \"{email.subject}\". "
            "I've seen your message and will come back to you with an answer soon.\n\nBest regards,")


def generate_day_summary(lines: list[str], fallback: str) -> tuple[str, bool]:
    """Returns (text, ai_generated). Uses the deterministic fallback if AI is off or fails."""
    s = get_settings()
    if not s.ai_enabled or not lines:
        return fallback, False
    messages = [
        {"role": "system", "content": (
            "You summarise a person's inbox for the day in 2 to 4 sentences: what "
            "matters most, what needs action, what can be ignored. English. "
            'Return ONLY JSON: {"summary": "..."}')},
        {"role": "user", "content": "\n".join(lines)[:6000]},
    ]
    try:
        raw = chat_json(s.classify_model, messages, max_tokens=1000, temperature=0.2)
        return SummaryOutput.model_validate(json.loads(raw)).summary.strip(), True
    except (AIError, json.JSONDecodeError, ValidationError):
        return fallback, False
